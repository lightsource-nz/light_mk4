//! AXS15231B controller driver over a QSPI display bus -- the LCD half of the combined
//! LCD-and-touch part on the Waveshare RP2350-Touch-LCD-3.49 (172x640). The chip has GDDRAM
//! and the familiar CASET/RASET/RAMWR windowing, so the chunk model fits unchanged; only the
//! bus framing differs, which [`light_core::hal::QspiDisplayBus`] carries.
//!
//! The init sequence is Waveshare's reference table for this exact panel, byte for byte --
//! vendor-tuned register soup with no datasheet to check it against, which is exactly why it
//! is copied rather than understood. Two notes from that source: the reference sends NO
//! SLPOUT/DISPON after the table (both appear commented out, and its demo verifiably lights
//! the glass), and the table opens and closes with the 0xBB unlock/lock pair.

use light_core::hal::{Clock, QspiDisplayBus};
use crate::display::{DisplayDriver, Frame, Region};

pub const CMD_CASET: u8 = 0x2A;
pub const CMD_RASET: u8 = 0x2B;
pub const CMD_RAMWR: u8 = 0x2C;

